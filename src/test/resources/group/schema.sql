-- 로컬 H2 Oracle 모드 전용. 팀 DB에 실행하지 않는다.
CREATE TABLE users(studentid INTEGER PRIMARY KEY,nickname VARCHAR(15));
CREATE TABLE post(postid INTEGER PRIMARY KEY,writerid INTEGER REFERENCES users(studentid),title VARCHAR(50),capacity INTEGER,acceptedcount INTEGER);
CREATE TABLE apply(applyid INTEGER PRIMARY KEY,applicantid INTEGER REFERENCES users(studentid),postid INTEGER REFERENCES post(postid),introduction VARCHAR(255),status VARCHAR(10),createat TIMESTAMP);
CREATE TABLE groups(groupid INTEGER PRIMARY KEY REFERENCES post(postid),capacity INTEGER,academicyear INTEGER,semester INTEGER,status VARCHAR(10));
CREATE TABLE group_member(groupid INTEGER REFERENCES groups(groupid),studentid INTEGER REFERENCES users(studentid),PRIMARY KEY(groupid,studentid));
CREATE TABLE role(roleid INTEGER PRIMARY KEY,groupid INTEGER NOT NULL REFERENCES groups(groupid),roletitle VARCHAR(100),assigneeid INTEGER REFERENCES users(studentid));
CREATE TABLE rule(ruleid INTEGER PRIMARY KEY,groupid INTEGER NOT NULL REFERENCES groups(groupid),content VARCHAR(100),UNIQUE(ruleid,groupid));
CREATE TABLE ruleagreement(ruleid INTEGER,groupid INTEGER,memberid INTEGER,PRIMARY KEY(ruleid,groupid,memberid),FOREIGN KEY(ruleid,groupid) REFERENCES rule(ruleid,groupid),FOREIGN KEY(groupid,memberid) REFERENCES group_member(groupid,studentid));
CREATE TABLE settlement(month VARCHAR(10),groupid INTEGER REFERENCES groups(groupid),settled CHAR(1) CHECK(settled IN('Y','N')),PRIMARY KEY(month,groupid));
CREATE TABLE settlementlist(listid INTEGER PRIMARY KEY,groupid INTEGER,month VARCHAR(10),itemname VARCHAR(50),payerid INTEGER REFERENCES users(studentid),listprice NUMBER(38,0) NOT NULL CHECK(listprice>0),FOREIGN KEY(month,groupid) REFERENCES settlement(month,groupid));
CREATE TABLE leavegroup(leaveid INTEGER PRIMARY KEY,groupid INTEGER REFERENCES groups(groupid),requesterid INTEGER REFERENCES users(studentid),reason VARCHAR(300),status VARCHAR(30) CHECK(status IN('PENDING','APPROVED','REJECTED')),UNIQUE(leaveid,groupid));
CREATE TABLE leaveconsent(leaveid INTEGER,groupid INTEGER,memberid INTEGER,agreed CHAR(1) CHECK(agreed IN('Y','N')),PRIMARY KEY(leaveid,groupid,memberid),FOREIGN KEY(leaveid,groupid) REFERENCES leavegroup(leaveid,groupid),FOREIGN KEY(groupid,memberid) REFERENCES group_member(groupid,studentid));
CREATE SEQUENCE RM_ROLE_SEQ START WITH 1001;
CREATE SEQUENCE RM_RULE_SEQ START WITH 1001;
CREATE SEQUENCE RM_SETTLEMENT_ITEM_SEQ START WITH 1001;
CREATE SEQUENCE RM_LEAVE_SEQ START WITH 1001;
